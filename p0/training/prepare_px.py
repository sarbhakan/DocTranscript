def sha256(path: Path) -> str:
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def text_key(text: str) -> str:
    """Conservative duplicate key; never normalize doses, fractions or meaning."""
    return " ".join(unicodedata.normalize("NFC", text).casefold().split())


def read_pcm(raw: bytes) -> bytes:
    try:
        with wave.open(io.BytesIO(raw), "rb") as stream:
            if (stream.getnchannels(), stream.getsampwidth(), stream.getframerate(),
                    stream.getcomptype()) != (1, 2, RATE, "NONE"):
                raise ValueError("WAV PCM16 mono 16 kHz requis")
            frames = stream.getnframes()
            if not 0 < frames <= RATE * 120:
                raise ValueError("WAV vide ou anormalement long")
            pcm = stream.readframes(frames)
            if len(pcm) != frames * 2:
                raise ValueError("WAV tronqué")
    except (EOFError, wave.Error) as error:
        raise ValueError("WAV invalide ou tronqué") from error
    return pcm


def canonical_wav(pcm: bytes) -> bytes:
    stream = io.BytesIO()
    with wave.open(stream, "wb") as output:
        output.setparams((1, 2, RATE, 0, "NONE", "not compressed"))
        output.writeframes(pcm)
    return stream.getvalue()


@contextmanager
def locked_archive(path: Path):
    # Hash and parse the SAME open file, not two independently resolved paths.
    with path.open("rb") as source:
        if hashlib.file_digest(source, "sha256").hexdigest() != PX_SHA256:
            raise ValueError("Archive refusée : empreinte différente de PxCorpus v4")
        source.seek(0)
        with ZipFile(source) as archive:
            yield archive


@dataclass(frozen=True)
class Row:
    index: int
    speaker: str
    category: str
    reference: str
    source_path: str
    frames: int
    pcm_sha256: str


def load_archive(archive: ZipFile) -> tuple[list[Row], dict[str, set[int]]]:
    names = archive.namelist()
    if len(names) != len(set(names)):
        raise ValueError("Entrées ZIP dupliquées")

    def lines(name):
        return archive.read(PX_PATH + name).decode("utf-8-sig").splitlines()

    paths, texts, tags, metadata = map(lines, ("paths.txt", "seq.in", "seq.out", "metadata.txt"))
    if not paths or not len(paths) == len(texts) == len(tags) == len(metadata):
        raise ValueError("Métadonnées PxSLU désalignées")
    if len(paths) != len(set(paths)):
        raise ValueError("Chemins audio dupliqués")
    splits = {}
    for name in ("train", "dev", "test"):
        values = [int(value) for value in lines(f"data_splits/{name}/{name}.txt") if value.strip()]
        if len(values) != len(set(values)) or any(not 0 <= i < len(paths) for i in values):
            raise ValueError("Indices de partition invalides")
        splits[name] = set(values)
    if (splits["train"] & splits["dev"] or splits["train"] & splits["test"]
            or splits["dev"] & splits["test"]
            or set.union(*splits.values()) != set(range(len(paths)))):
        raise ValueError("Partitions source incomplètes ou superposées")

    rows, categories = [], {}
    for index, (path, reference, markers, meta) in enumerate(zip(paths, texts, tags, metadata)):
        # Never extract paths provided by the archive onto the local filesystem.
        if not re.fullmatch(r"[A-Za-z0-9]+/recording_\d+\.wav", path):
            raise ValueError("Chemin audio PxSLU invalide")
        fields = next(csv.reader([meta]))
        if len(fields) != 4 or not fields[0].isdigit() or fields[3] not in {"doctor", "expert", "non-expert"}:
            raise ValueError("Identifiant de locuteur ou catégorie invalide")
        speaker, category = "px-" + fields[0], fields[3]
        if categories.setdefault(speaker, category) != category:
            raise ValueError("Catégorie incohérente pour un locuteur")
        if not reference.strip() or len(reference.split()) != len(markers.split()):
            raise ValueError("Référence vide ou annotation désalignée")
        if (index in splits["test"]) != (category == "doctor"):
            raise ValueError("Le test officiel doit réserver les médecins")
        source_path = PX_PATH + "recordings/" + path
        pcm = read_pcm(archive.read(source_path))
        rows.append(Row(index, speaker, category, reference, source_path,
                        len(pcm) // 2, hashlib.sha256(pcm).hexdigest()))
    return rows, splits


def build_plan(rows: list[Row], source_splits: dict[str, set[int]]) -> tuple[dict, dict, dict]:
    by_index = {row.index: row for row in rows}
    known = BENCHMARK_ROWS | PRIOR_ROWS
    if not known <= by_index.keys() or not BENCHMARK_ROWS <= source_splits["test"]:
        raise ValueError("Les cas du benchmark verrouillé sont absents")
    reserve_indices = source_splits["test"] | known
    reserve_speakers = {by_index[i].speaker for i in reserve_indices}
    reserved = [row for row in rows if row.speaker in reserve_speakers]
    reserve_texts = {text_key(row.reference) for row in reserved}
    reserve_audio = {row.pcm_sha256 for row in reserved}
    speakers = {row.speaker for row in rows} - reserve_speakers
    if len(speakers) < 2:
        raise ValueError("Pas assez de locuteurs indépendants après exclusion")
    ranked = sorted(speakers, key=lambda speaker: hashlib.sha256(
        (SPLIT_KEY + "\0" + speaker).encode("utf-8")).digest())
    validation = set(ranked[:math.ceil(len(ranked) / 5)])
    partitions = {"train": [], "validation": []}
    reasons = Counter()
    excluded = []
    for row in rows:
        if row.speaker in reserve_speakers:
            reason = "reserved_speaker"
        elif text_key(row.reference) in reserve_texts:
            reason = "reference_matches_reserve"
        elif row.pcm_sha256 in reserve_audio:
            reason = "pcm_matches_reserve"
        elif row.frames > MAX_SECONDS * RATE:
            reason = "longer_than_30_seconds"
        else:
            partitions["validation" if row.speaker in validation else "train"].append(row)
            continue
        reasons[reason] += 1
        excluded.append({"index": row.index, "reason": reason})

    # Preserve the split fixed by speaker. Remove shared references/audio from
    # BOTH partitions instead of moving a person's utterance to another split.
    def intersection(key):
        return {key(r) for r in partitions["train"]} & {key(r) for r in partitions["validation"]}
    shared_texts = intersection(lambda r: text_key(r.reference))
    shared_audio = intersection(lambda r: r.pcm_sha256)
    for name, items in partitions.items():
        keep, seen_audio = [], set()
        for row in items:
            if text_key(row.reference) in shared_texts:
                reason = "reference_crosses_partitions"
            elif row.pcm_sha256 in shared_audio:
                reason = "pcm_crosses_partitions"
            elif row.pcm_sha256 in seen_audio:
                reason = "duplicate_pcm_in_partition"
            else:
                keep.append(row)
                seen_audio.add(row.pcm_sha256)
                continue
            reasons[reason] += 1
            excluded.append({"index": row.index, "reason": reason})
        if not keep:
            raise ValueError("Partition vide après contrôle des fuites")
        partitions[name] = keep
    reserve = {"speakers": sorted(reserve_speakers), "reference_keys": sorted(reserve_texts),
               "pcm_sha256": sorted(reserve_audio), "excluded_rows": sorted(excluded, key=lambda r: r["index"])}
    report = {
        "source_rows": len(rows), "source_speakers": len({r.speaker for r in rows}),
        "source_train_dev_shared_speakers": len({by_index[i].speaker for i in source_splits["train"]}
                                                 & {by_index[i].speaker for i in source_splits["dev"]}),
        "protected_benchmark_rows": len(BENCHMARK_ROWS), "protected_prior_rows": len(PRIOR_ROWS),
        "reserved_rows": len(reserved), "reserved_speakers": len(reserve_speakers),
        "excluded_by_reason": dict(sorted(reasons.items())),
        "partition_policy": "20% of eligible speakers by fixed SHA-256 rank; shared texts/PCM removed from both",
        "split_key": SPLIT_KEY,
    }
    return partitions, reserve, report


def write_json(path: Path, value):
    path.write_text(json.dumps(value, ensure_ascii=False, sort_keys=True, indent=2) + "\n", encoding="utf-8")


def safe_artifact(root: Path, relative: str | PurePosixPath) -> Path:
    path = root
    for part in PurePosixPath(relative).parts:
        if part in {".", "..", "/"}:
            raise ValueError("Chemin d’artefact non conforme")
        path = path / part
        if path.is_symlink() or getattr(path, "is_junction", lambda: False)():
            raise ValueError("Les liens sont interdits dans le corpus")
    if not path.is_file() or not path.resolve(strict=True).is_relative_to(root):
        raise ValueError("L’artefact doit rester dans le corpus local")
    return path


def entry_for(row: Row, partition: str, audio_sha256: str) -> dict:
    return {"id": f"px-{row.index}", "dataset": DATASET, "licence": LICENSE,
            "partition": partition, "speaker_id": row.speaker, "category": row.category,
            "source_row_index": row.index, "audio_filepath": f"wav/px-{row.index}.wav",
            "audio_sha256": audio_sha256, "pcm_sha256": row.pcm_sha256,
            "duration": row.frames / RATE, "text": row.reference}


def verify_export(root: Path, archive_path: Path) -> dict:
    if root.is_symlink() or getattr(root, "is_junction", lambda: False)():
        raise ValueError("La racine du corpus ne doit pas être un lien")
    root = root.resolve(strict=True)
    report = json.loads(safe_artifact(root, "report.json").read_text(encoding="utf-8"))
    if (report.get("schema") != 1 or report.get("dataset") != DATASET
            or report.get("source_sha256") != PX_SHA256 or report.get("development_only") is not True
            or report.get("source_url") != SOURCE_URL or report.get("upstream_pretraining_overlap") != "unknown"
            or report.get("licence") != LICENSE or report.get("training_performed") is not False):
        raise ValueError("Source non autorisée : uniquement PxCorpus v4 verrouillé")
    for name, expected in report["artifacts_sha256"].items():
        if name not in {"train.jsonl", "validation.jsonl", "reserve.local.json", "ATTRIBUTION.txt"}:
            raise ValueError("Artefact inattendu")
        if sha256(safe_artifact(root, name)) != expected:
            raise ValueError("Artefact modifié")
    if set(report["artifacts_sha256"]) != {"train.jsonl", "validation.jsonl", "reserve.local.json", "ATTRIBUTION.txt"}:
        raise ValueError("Empreintes d’artefacts incomplètes")
    # The self-declared hashes alone do not authenticate labels or speakers.
    # Rebuild the expected partition from the independently locked source.
    with locked_archive(archive_path) as archive:
        source_rows, source_splits = load_archive(archive)
    expected_partitions, expected_reserve, expected_report = build_plan(source_rows, source_splits)
    reserve = json.loads(safe_artifact(root, "reserve.local.json").read_text(encoding="utf-8"))
    if reserve != expected_reserve:
        raise ValueError("Réserve différente de l’archive source verrouillée")
    if safe_artifact(root, "ATTRIBUTION.txt").read_text(encoding="utf-8") != NOTICE:
        raise ValueError("Attribution différente de celle prévue")
    if any(report.get(key) != value for key, value in expected_report.items()):
        raise ValueError("Rapport différent du plan reconstruit depuis la source")
    reserved = {"speaker": set(reserve["speakers"]), "reference": set(reserve["reference_keys"]),
                "pcm": set(reserve["pcm_sha256"])}
    seen = {kind: set() for kind in ("id", "speaker", "reference", "pcm")}
    summary = {}
    for partition in ("train", "validation"):
        expected_rows = {f"px-{row.index}": row for row in expected_partitions[partition]}
        local = {kind: set() for kind in seen}
        seconds, count, categories = 0.0, 0, Counter()
        for line in safe_artifact(root, f"{partition}.jsonl").read_text(encoding="utf-8").splitlines():
            row = json.loads(line)
            if row.get("dataset") != DATASET or row.get("licence") != LICENSE or row.get("partition") != partition:
                raise ValueError("Jeu, licence ou partition non conforme")
            if (not isinstance(row.get("id"), str) or not re.fullmatch(r"px-\d+", row["id"])
                    or not isinstance(row.get("speaker_id"), str) or not re.fullmatch(r"px-\d+", row["speaker_id"])
                    or not isinstance(row.get("text"), str) or not row["text"].strip()
                    or row.get("category") not in {"expert", "non-expert"}):
                raise ValueError("Métadonnées d’adaptation invalides")
            relative = PurePosixPath(row["audio_filepath"])
            if relative.as_posix() != f"wav/{row['id']}.wav":
                raise ValueError("Chemin WAV non conforme")
            audio = safe_artifact(root, relative)
            raw = audio.read_bytes()
            pcm = read_pcm(raw)
            duration = len(pcm) / (2 * RATE)
            if (hashlib.sha256(raw).hexdigest() != row["audio_sha256"]
                    or hashlib.sha256(pcm).hexdigest() != row["pcm_sha256"]
                    or not 0 < duration <= MAX_SECONDS or duration != row["duration"]):
                raise ValueError("Empreinte ou durée WAV incorrecte")
            keys = {"id": row["id"], "speaker": row["speaker_id"],
                    "reference": text_key(row["text"]), "pcm": row["pcm_sha256"]}
            if keys["id"] in local["id"] or keys["pcm"] in local["pcm"]:
                raise ValueError("Audio ou identifiant dupliqué dans une partition")
            for kind, value in keys.items():
                if value in seen[kind] or value in reserved.get(kind, set()):
                    raise ValueError("Fuite entre partitions ou vers la réserve benchmark")
                local[kind].add(value)
            original = expected_rows.get(row["id"])
            if (original is None or type(row.get("source_row_index")) is not int
                    or row != entry_for(original, partition, hashlib.sha256(raw).hexdigest())
                    or raw != canonical_wav(pcm)):
                raise ValueError("Entrée différente de la référence, voix ou audio source")
            seconds += duration
            categories[row["category"]] += 1
            count += 1
        if not count:
            raise ValueError("Partition vide")
        if local["id"] != expected_rows.keys():
            raise ValueError("Partition source incomplète")
        summary[partition] = {"rows": count, "speakers": len(local["speaker"]),
                              "seconds": round(seconds, 4), "categories": dict(sorted(categories.items()))}
        for kind in seen:
            seen[kind].update(local[kind])
    if report.get("partitions") != summary:
        raise ValueError("Agrégats du rapport incohérents")
    return summary


def export(archive_path: Path, output: Path) -> dict:
    # A corpus cannot be substituted by Corti, PARROT, ASR outputs or arbitrary
    # local medical data. There is intentionally no --skip-hash or source flag.
    output = output.expanduser().resolve()
    repository = Path(__file__).resolve().parents[2]
    if output.is_relative_to(repository):
        raise ValueError("Choisir une sortie locale hors du dépôt Git")
    if output.exists():
        raise ValueError("Le dossier de sortie existe déjà")
    output.parent.mkdir(parents=True, exist_ok=True)
    with locked_archive(archive_path) as archive:
        rows, splits = load_archive(archive)
        partitions, reserve, report = build_plan(rows, splits)
        with tempfile.TemporaryDirectory(prefix=".notevive-px-", dir=output.parent) as temporary:
            stage = Path(temporary) / "export"
            (stage / "wav").mkdir(parents=True)
            summaries = {}
            for name, items in partitions.items():
                entries = []
                for row in items:
                    pcm = read_pcm(archive.read(row.source_path))
                    if hashlib.sha256(pcm).hexdigest() != row.pcm_sha256:
                        raise ValueError("Audio source changé pendant l’export")
                    relative = f"wav/px-{row.index}.wav"
                    path = stage / relative
                    path.write_bytes(canonical_wav(pcm))
                    entries.append(entry_for(row, name, sha256(path)))
                (stage / f"{name}.jsonl").write_text("".join(
                    json.dumps(entry, ensure_ascii=False, sort_keys=True) + "\n" for entry in entries), encoding="utf-8")
                summaries[name] = {"rows": len(items), "speakers": len({r.speaker for r in items}),
                                   "seconds": round(sum(r.frames for r in items) / RATE, 4),
                                   "categories": dict(sorted(Counter(r.category for r in items).items()))}
            write_json(stage / "reserve.local.json", reserve)
            (stage / "ATTRIBUTION.txt").write_text(NOTICE, encoding="utf-8")
            report.update({"schema": 1, "dataset": DATASET, "licence": LICENSE,
                           "source_url": SOURCE_URL, "source_sha256": PX_SHA256,
                           "development_only": True, "training_performed": False,
                           "upstream_pretraining_overlap": "unknown",
                           "references": "source seq.in, not independently re-audited; no ASR-generated labels",
                           "partitions": summaries, "leakage_check": "speaker, normalized-reference and PCM intersections empty",
                           "artifacts_sha256": {name: sha256(stage / name) for name in
                                                ("train.jsonl", "validation.jsonl", "reserve.local.json", "ATTRIBUTION.txt")}})
            write_json(stage / "report.json", report)
            verify_export(stage, archive_path)
            if output.exists():
                raise ValueError("Le dossier de sortie existe déjà")
            stage.rename(output)
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    prepare = commands.add_parser("export", help="Export local sans entraîner de modèle")
    prepare.add_argument("--px-archive", type=Path, required=True)
    prepare.add_argument("--output", type=Path, required=True)
    verify = commands.add_parser("verify", help="Recontrôler audio, empreintes et séparation")
    verify.add_argument("--directory", type=Path, required=True)
    verify.add_argument("--px-archive", type=Path, required=True)
    args = parser.parse_args()
    try:
        result = export(args.px_archive, args.output)["partitions"] if args.command == "export" else verify_export(args.directory, args.px_archive)
    except (ValueError, OSError, KeyError, TypeError, BadZipFile, wave.Error) as error:
        parser.exit(1, f"Export/vérification refusé : {error}\n")
    print(json.dumps({"training_performed": False, "verified_partitions": result}, ensure_ascii=False, sort_keys=True))


if __name__ == "__main__":
    main()
